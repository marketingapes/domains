"""Write src/stores.js (store allow-list for the Worker) from ../adsense-builders/ddm/coupons_feed.json."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
f = json.load(open(os.path.join(H, "..", "adsense-builders", "ddm", "coupons_feed.json")))
rows = [{"slug": s["slug"], "name": s["name"], "advertiser_names": s.get("advertiser_names", [])} for s in f["stores"]]
open(os.path.join(H, "src", "stores.js"), "w").write("// Generated by make_stores.py. Do not edit.\nexport default " + json.dumps(rows, ensure_ascii=False) + ";\n")
print(len(rows), "stores")
